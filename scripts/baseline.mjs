// Jednorazová oprava histórie migrácií (keď v priečinku prisma/migrations chýbajú staré migrácie).
// Postup: databáza sa najprv zosúladí cez `prisma db push`, potom tento skript:
//  1. starý priečinok migrácií odloží ako zálohu (nič nemaže),
//  2. vytvorí jednu východiskovú migráciu 0_baseline podľa aktuálnej schémy,
//  3. v databáze vymaže len ZÁZNAMY o starých migráciách (tabuľky a dáta ostanú),
//  4. označí 0_baseline ako už vykonanú.
// Spustenie v priečinku projektu:  node scripts/baseline.mjs

import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const bin = process.platform === 'win32' ? path.join('node_modules', '.bin', 'prisma.cmd') : path.join('node_modules', '.bin', 'prisma');
if (!fs.existsSync(bin)) {
  console.error('Chýba Prisma v projekte. Najprv spusti: npm install');
  process.exit(1);
}
const run = (args, opts = {}) => execSync(`"${bin}" ${args}`, { encoding: 'utf8', ...opts });

const dir = path.join('prisma', 'migrations');
if (fs.existsSync(dir)) {
  const backup = path.join('prisma', `migrations_zaloha_${Date.now()}`);
  fs.renameSync(dir, backup);
  console.log(`Starý priečinok migrácií odložený do ${backup}`);
}

console.log('Vytváram východiskovú migráciu 0_baseline…');
const sql = run('migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma --script', { stdio: ['ignore', 'pipe', 'inherit'] });
fs.mkdirSync(path.join(dir, '0_baseline'), { recursive: true });
fs.writeFileSync(path.join(dir, '0_baseline', 'migration.sql'), sql, 'utf8');
fs.writeFileSync(path.join(dir, 'migration_lock.toml'), '# Please do not edit this file manually\nprovider = "postgresql"\n', 'utf8');

console.log('Mažem len záznamy o starých migráciách (tabuľky a dáta ostávajú)…');
run('db execute --schema prisma/schema.prisma --stdin', { input: 'DELETE FROM "_prisma_migrations";', stdio: ['pipe', 'inherit', 'inherit'] });

console.log('Označujem 0_baseline ako vykonanú…');
run('migrate resolve --applied 0_baseline', { stdio: 'inherit' });
run('migrate status', { stdio: 'inherit' });
console.log('\nHotovo. História migrácií je opravená. Priečinok prisma/migrations pridaj do gitu.');
